/**
 * The launcher ACP clients start: a tiny script that runs the stdio bridge with
 * the Node.js runtime of the DSH process that wrote it. DSH Desktop runs on
 * Electron, so a machine without a separate Node.js installation still works.
 *
 * The script outlives DSH: when DSH stops, the launcher stays so that an editor can
 * start DSH again. It does not outlive the plugin: a plugin unloaded while DSH runs
 * on withdraws it (see {@link withdrawLauncher}). When the plugin or the app it
 * points at is gone anyway, the script says so and exits 1, instead of leaving the
 * editor a runtime error.
 */

import { randomUUID } from 'node:crypto'
import { existsSync } from 'node:fs'
import { chmod, mkdir, readFile, rename, rm, rmdir, writeFile } from 'node:fs/promises'
import { dirname, join, posix, win32 } from 'node:path'
import type { EndpointRecord } from './endpoint.js'
import { endpointsDirectory, launcherPath, socketsDirectory } from './paths.js'

export interface LauncherTarget {
  /** Executable that runs JavaScript: Node.js, or Electron in Node mode. */
  runtime: string
  /** Whether `runtime` is Electron and needs `ELECTRON_RUN_AS_NODE`. */
  electron: boolean
  /** Absolute path of the stdio bridge script. */
  script: string
}

const PLUGIN = '@agents-anywhere/dsh-acp-bridge'

function posixQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`
}

/** Batch files expand `%`; Windows paths cannot contain `"`. */
function batchQuote(value: string): string {
  return `"${value.replaceAll('%', '%%')}"`
}

/** Text for an unquoted `echo` in a batch file. */
function batchEcho(value: string): string {
  return value.replace(/[\^&|<>]/gu, '^$&').replaceAll('%', '%%')
}

function missingPlugin(script: string): string {
  return `dsh-acp-bridge: 找不到插件文件 ${script}：插件可能已从 DSH 中移除。请在 DSH 中重新安装并启用插件 ${PLUGIN}，DSH 会重新生成这个启动脚本。`
}

function missingRuntime(runtime: string): string {
  // An AppImage's files exist only while that AppImage runs, under a mount point named after it.
  return /\/\.mount_[^/]+\//u.test(runtime)
    ? `dsh-acp-bridge: DSH 没有在运行：AppImage 版的 DSH 运行时才能使用这个启动脚本，请先打开 DSH。`
    : `dsh-acp-bridge: 找不到 DSH 程序 ${runtime}：DSH 可能已卸载或移动。打开 DSH 后会重新生成这个启动脚本。`
}

export function launcherScript(target: LauncherTarget, platform: NodeJS.Platform = process.platform): string {
  // A bare command name (Node.js from PATH) is left to the shell to find.
  const checkRuntime = (platform === 'win32' ? win32 : posix).isAbsolute(target.runtime)
  if (platform === 'win32') {
    return [
      '@echo off',
      'rem Generated by @agents-anywhere/dsh-acp-bridge; DSH rewrites it whenever the plugin starts.',
      'setlocal',
      `if not exist ${batchQuote(target.script)} goto missing_plugin`,
      ...(checkRuntime ? [`if not exist ${batchQuote(target.runtime)} goto missing_runtime`] : []),
      ...(target.electron ? ['set ELECTRON_RUN_AS_NODE=1'] : []),
      `${batchQuote(target.runtime)} ${batchQuote(target.script)} %*`,
      'exit /b %ERRORLEVEL%',
      // cmd reads each line as it runs it, so the messages below are read as UTF-8.
      ':missing_plugin',
      'chcp 65001 >nul',
      `>&2 echo ${batchEcho(missingPlugin(target.script))}`,
      'exit /b 1',
      ':missing_runtime',
      'chcp 65001 >nul',
      `>&2 echo ${batchEcho(missingRuntime(target.runtime))}`,
      'exit /b 1',
      '',
    ].join('\r\n')
  }
  return [
    '#!/bin/sh',
    '# Generated by @agents-anywhere/dsh-acp-bridge; DSH rewrites it whenever the plugin starts.',
    `if [ ! -f ${posixQuote(target.script)} ]; then printf '%s\\n' ${posixQuote(missingPlugin(target.script))} >&2; exit 1; fi`,
    ...(checkRuntime
      ? [`if [ ! -x ${posixQuote(target.runtime)} ]; then printf '%s\\n' ${posixQuote(missingRuntime(target.runtime))} >&2; exit 1; fi`]
      : []),
    `${target.electron ? 'ELECTRON_RUN_AS_NODE=1 ' : ''}exec ${posixQuote(target.runtime)} ${posixQuote(target.script)} "$@"`,
    '',
  ].join('\n')
}

/** Replace the launcher atomically; returns its path. */
export async function writeLauncher(home: string, target: LauncherTarget, platform: NodeJS.Platform = process.platform): Promise<string> {
  const path = launcherPath(home, platform)
  await mkdir(dirname(path), { recursive: true, mode: 0o700 })
  const temporary = join(dirname(path), `.launcher.${randomUUID()}.tmp`)
  try {
    await writeFile(temporary, launcherScript(target, platform), { mode: 0o700, flag: 'wx' })
    if (platform !== 'win32') await chmod(temporary, 0o700)
    await rename(temporary, path)
  } catch (error) {
    await rm(temporary, { force: true }).catch(() => undefined)
    throw error
  }
  return path
}

/** What becomes of the launcher when the plugin instance that wrote it unloads while DSH runs on. */
export type LauncherSuccession = { action: 'keep' } | { action: 'remove' } | { action: 'write', target: LauncherTarget }

/**
 * Decide what becomes of the launcher.
 * @param own - what the unloading instance wrote.
 * @param current - the launcher as it is now; undefined when it is gone.
 * @param others - records of the other running instances, newest first.
 * @param exists - whether a path exists.
 * @returns keep a launcher another instance wrote since; otherwise hand it to the newest other instance whose
 * plugin and program still exist, or remove it.
 */
export function launcherSuccession(own: LauncherTarget, current: string | undefined, others: readonly EndpointRecord[],
  exists: (path: string) => boolean, platform: NodeJS.Platform = process.platform): LauncherSuccession {
  if (current === undefined || current !== launcherScript(own, platform)) return { action: 'keep' }
  const absolute = (platform === 'win32' ? win32 : posix).isAbsolute
  const heir = others.map(record => record.launcher).find((target): target is LauncherTarget => target !== undefined
    && exists(target.script) && (!absolute(target.runtime) || exists(target.runtime)))
  return heir ? { action: 'write', target: heir } : { action: 'remove' }
}

/**
 * The plugin instance unloaded while DSH runs on (disabled, removed, uninstalled or reloaded): its launcher has
 * nothing behind it any more. Another running instance takes it over, or it is removed together with the
 * directories the plugin made once they are empty. Not for a DSH that stops: its launcher stays.
 */
export async function withdrawLauncher(home: string, own: LauncherTarget, others: readonly EndpointRecord[],
  platform: NodeJS.Platform = process.platform): Promise<LauncherSuccession> {
  const path = launcherPath(home, platform)
  const succession = launcherSuccession(own, await readFile(path, 'utf8').catch(() => undefined), others, existsSync, platform)
  if (succession.action === 'write') await writeLauncher(home, succession.target, platform)
  if (succession.action === 'remove') {
    await rm(path, { force: true })
    // rmdir removes only empty directories: anything another instance keeps there stays, the home last.
    for (const directory of [dirname(path), endpointsDirectory(home), socketsDirectory(home), home]) {
      await rmdir(directory).catch(() => undefined)
    }
  }
  return succession
}
