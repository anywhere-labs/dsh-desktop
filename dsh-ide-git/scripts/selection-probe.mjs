/**
 * Selection probe (issue #13): drives a RUNNING clean dsh web instance and
 * locks the multi-select episode end to end.
 *
 * What it asserts, in order:
 *   1. Ctrl+click toggles change rows and Shift+click spans them; the
 *      selection bar appears with the live count;
 *   2. Ctrl+A selects everything but ignored, Esc clears;
 *   3. a rubber-band drag across the windowed list selects the rows it
 *      crosses (and swallows the trailing click);
 *   4. right-clicking the selection offers bulk verbs; staging them really
 *      moves the rows into the staged group;
 *   5. Backspace opens the grouped discard confirm (cancelled — nothing is
 *      destroyed);
 *   6. Ctrl+C copies the selected paths (clipboard read-back);
 *   7. the branch tree: Ctrl+click picks two branches, Ctrl+C copies their
 *      names, the right-click menu offers the grouped delete (cancelled);
 *   8. the history: Ctrl+click picks two commits, the menu offers copy +
 *      cherry-pick, Ctrl+C copies full hashes;
 *   9. zero uncaught page errors throughout.
 *
 *   node scripts/selection-probe.mjs "http://127.0.0.1:3099/?token=…" [out-dir]
 *
 * The instance is expected to be clean-isolated (independent DSH_HOME, port
 * 3099) with dsh-better-sidebar + dsh-ide-git installed. The probe binds the
 * workspace 演示仓库 to a git repository ITSELF: pass the absolute REALPATH of
 * a git work tree through DIG_PROBE_REPO (default /private/tmp/dsh-ide-git-demo,
 * as generated by scripts/demo-repo.mjs — mind macOS /tmp → /private/tmp).
 *
 * Playwright is loaded from the DSH checkout (DSH_CHECKOUT overrides the path).
 */
import { createRequire } from 'node:module'
import { mkdirSync, readdirSync, existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { join } from 'node:path'

const url = process.argv[2]
if (url === undefined || url === '') {
  console.error('usage: node scripts/selection-probe.mjs <web-url-with-token> [out-dir]')
  process.exit(1)
}
const outDir = process.argv[3] === undefined || process.argv[3] === '' ? '/tmp/selection-probe' : process.argv[3]
mkdirSync(outDir, { recursive: true })
const repoPath = process.env.DIG_PROBE_REPO === undefined ? '/private/tmp/dsh-ide-git-demo' : process.env.DIG_PROBE_REPO
const workspaceTitle = process.env.DIG_PROBE_WORKSPACE === undefined ? '演示仓库' : process.env.DIG_PROBE_WORKSPACE

function loadPlaywright() {
  const checkout = process.env.DSH_CHECKOUT === undefined || process.env.DSH_CHECKOUT === ''
    ? '/Users/kanna/project/deepseek-harness'
    : process.env.DSH_CHECKOUT
  const store = join(checkout, 'node_modules', '.pnpm')
  const candidates = []
  if (existsSync(store)) {
    for (const name of readdirSync(store)) {
      if (name.indexOf('playwright@') !== 0) continue
      candidates.push(join(store, name, 'node_modules', 'playwright', 'package.json'))
    }
  }
  candidates.push(join(checkout, 'node_modules', 'playwright', 'package.json'))
  for (const candidate of candidates) {
    if (!existsSync(candidate)) continue
    try { return createRequire(candidate)('playwright') } catch (error) { void error }
  }
  throw new Error('playwright not found under ' + checkout + ' (set DSH_CHECKOUT)')
}

const { chromium } = loadPlaywright()
const browser = await chromium.launch({ headless: true, channel: process.env.DSH_SHOT_CHANNEL === undefined ? 'chrome' : process.env.DSH_SHOT_CHANNEL })
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 1 })
await context.grantPermissions(['clipboard-read', 'clipboard-write'])
const page = await context.newPage()

const failures = []
const check = (ok, message) => {
  console.log((ok === true ? '✔' : '✖') + ' ' + message)
  if (ok !== true) failures.push(message)
  return ok
}
const settle = (ms) => page.waitForTimeout(ms === undefined ? 900 : ms)

/* Reset the demo repository so the row/group layout the assertions rely on
   (staged: toolbar.js · unstaged: list.js · untracked: 3 entries) is
   deterministic — a previous probe run stages files as it goes. The generator
   is idempotent (it removes and rebuilds the directory); the workspace keeps
   pointing at the same realpath, so the session survives. */
try {
  execFileSync(process.execPath, [join(import.meta.dirname, 'demo-repo.mjs'), repoPath.replace(/^\/private/, '')], { stdio: 'pipe' })
  console.log('demo repository reset: ' + repoPath)
} catch (error) {
  console.log('demo repository reset FAILED: ' + String(error).slice(0, 160))
}

const pageErrors = []
page.on('pageerror', (error) => {
  pageErrors.push(String(error.message))
  console.log('PAGEERROR ' + String(error.message).slice(0, 300))
})

async function clickText(text, wait) {
  const locators = [page.getByRole('button', { name: text, exact: true }), page.getByText(text, { exact: true })]
  for (const locator of locators) {
    try {
      const target = locator.first()
      if (await target.count() === 0) continue
      await target.click({ timeout: 6000 })
      await settle(wait === undefined ? 1200 : wait)
      return true
    } catch (error) { void error }
  }
  console.log('MISS ' + text)
  return false
}

/* ---- enter: gate → workspace(@ DIG_PROBE_REPO) → session ----
   The workspace is created through the host gateway (POST /api/workspace/create,
   typert wire: {type:'client-request', rpcId, method:'workspace/create',
   payload:{args:{request:{path,title}}}}) — the UI dialog needs the host
   directoryPicker service, which is not guaranteed in a minimal checkout.
   Existing-workspace conflicts are ignored (idempotent setup). */
async function enter() {
  await page.goto(url, { waitUntil: 'domcontentloaded' })
  await settle(8000)
  for (let attempt = 0; attempt < 2; attempt++) {
    if (await clickText('继续', 1500) === false) break
  }
  const key = page.locator('input[type="password"]').first()
  if (await key.count() > 0) {
    await key.click({ timeout: 6000 })
    await page.keyboard.type('sk-selection-probe-dummy')
    await page.getByRole('button', { name: '保存并继续' }).first().click({ timeout: 6000 })
    await settle(2000)
  }
  const created = await page.evaluate(async (request) => {
    const token = new URLSearchParams(location.search).get('token') || ''
    const res = await fetch('/api/workspace/create?token=' + encodeURIComponent(token), {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ type: 'client-request', rpcId: 'selection-probe', method: 'workspace/create', payload: { args: { request: request } } }),
    })
    const text = await res.text()
    return { status: res.status, ok: text.indexOf('"ok":true') >= 0 || text.indexOf('already') >= 0, text: text.slice(0, 160) }
  }, { path: repoPath, title: workspaceTitle })
  console.log('workspace create: ' + JSON.stringify(created))
  /* Session inside the workspace: the 新会话 menu lists workspaces. */
  let bound = false
  try {
    await page.locator('button', { hasText: '新会话' }).first().click({ timeout: 6000 })
    await settle(1200)
    await page.getByText(workspaceTitle, { exact: true }).last().click({ timeout: 6000 })
    await settle(3000)
    bound = true
  } catch (error) { void error }
  if (bound === false) {
    console.log('MISS new-session bind (workspace may already be attached)')
  }
  const editor = page.locator('textarea, [contenteditable="true"]').first()
  await editor.click({ timeout: 8000 })
  await page.keyboard.type('selection probe')
  await page.getByRole('button', { name: '发送消息', exact: true }).first().click({ timeout: 8000 })
  await settle(5000)
}

/* The panel door, panes-probe style. */
const guideCard = async () => {
  for (const selector of ['[data-sidebar-right-guide-entry="dsh-ide-git:panel"]', '[data-sidebar-right-guide-entry="ide-git"]']) {
    const found = page.locator(selector).first()
    if (await found.count() > 0) return found
  }
  const described = page.locator('button').filter({ hasText: 'IDE 级 Git 面板' }).first()
  return await described.count() > 0 ? described : null
}

async function ensurePanel() {
  if (await page.locator('.dig-root:visible').count() > 0) return true
  let card = await guideCard()
  if (card === null) await clickText('打开右侧边栏', 2500)
  card = await guideCard()
  if (card === null) { console.log('MISS Git card'); return false }
  await card.click({ timeout: 8000 })
  await settle(4000)
  return await page.locator('.dig-root:visible').count() > 0
}

const changeRows = () => page.locator('.dig-changes-list .dig-row-file')
const selectedRows = () => page.locator('.dig-changes-list .dig-row-file.dig-row-selected')
const selectionBar = () => page.locator('.dig-selection-bar')

try {
  await enter()
  check(await ensurePanel() === true, 'panel mounted with repository data')
  await settle(2500)

  /* ---- 1-2. Ctrl+click toggle / Shift+click span + the selection bar ---- */
  const rowCount = await changeRows().count()
  check(rowCount >= 3, 'change list has rows to select (saw ' + rowCount + ')')
  /* FRESH-SHIFT first (regression lock for the anchorless-Shift fix): the panel
     just mounted, no plain click has ever set an anchor — Shift+click must
     span from the FIRST row, not silently degrade to single-select. */
  await changeRows().nth(2).click({ modifiers: ['Shift'] })
  await settle(400)
  check(await selectedRows().count() === 3, 'Shift+click with no anchor spans from the first row (saw ' + await selectedRows().count() + ')')
  await page.keyboard.press('Escape')
  await settle(300)
  await changeRows().nth(0).click({ modifiers: ['Meta'] })
  await settle(400)
  check(await selectedRows().count() === 1, 'Ctrl+click selects the first row')
  check(await selectionBar().count() === 1, 'selection bar appears')
  await changeRows().nth(1).click({ modifiers: ['Meta'] })
  await settle(400)
  check(await selectedRows().count() === 2, 'Ctrl+click toggles a second row in')
  await changeRows().nth(rowCount - 1).click({ modifiers: ['Shift'] })
  await settle(400)
  check(await selectedRows().count() >= 2, 'Shift+click spans from the anchor')
  const barText = await selectionBar().textContent()
  check(barText !== null && /\d/.test(barText) === true, 'selection bar shows a count (' + String(barText).slice(0, 40) + ')')

  /* ---- 3. Ctrl+A / Esc ---- */
  await changeRows().nth(0).click({ modifiers: ['Meta'] })
  await settle(200)
  await changeRows().nth(0).click({ modifiers: ['Meta'] })
  await settle(200)
  await page.locator('.dig-changes-list').focus()
  await page.keyboard.press('Control+a')
  await settle(400)
  check(await selectedRows().count() === rowCount, 'Ctrl+A selects every non-ignored row')
  await page.keyboard.press('Escape')
  await settle(400)
  check(await selectedRows().count() === 0 && await selectionBar().count() === 0, 'Esc clears the selection')

  /* ---- 4. rubber-band drag ---- */
  const list = page.locator('.dig-changes-list')
  const box = await list.boundingBox()
  if (box !== null && box.height > 160) {
    const x = box.x + box.width / 2
    await page.mouse.move(x, box.y + box.height - 8)
    await page.mouse.down()
    await page.mouse.move(x, box.y + 30, { steps: 10 })
    await page.mouse.up()
    await settle(500)
    const marqueeCount = await selectedRows().count()
    check(marqueeCount >= 2, 'rubber-band drag selects the crossed rows (saw ' + marqueeCount + ')')
    await page.keyboard.press('Escape')
    await settle(300)
  } else {
    check(false, 'change list tall enough for a rubber-band drag')
  }

  /* ---- 5. bulk stage through the right-click menu ----
     Rows 1 and 2 are NON-staged (row 0 sits in the staged group), so the
     bulk menu offers 暂存 2. */
  await changeRows().nth(1).click({ modifiers: ['Meta'] })
  await settle(300)
  await changeRows().nth(2).click({ modifiers: ['Meta'] })
  await settle(300)
  const twoSelected = await selectedRows().count()
  await changeRows().nth(2).click({ button: 'right' })
  await settle(600)
  const menuText = await page.evaluate(() => Array.from(document.querySelectorAll('.dig-menu')).map((m) => m.textContent || '').join('|'))
  check(twoSelected === 2 && menuText !== null && /暂存 2|Stage 2/.test(menuText) === true,
    'right-click on the selection offers bulk verbs (' + String(menuText).replace(/\s+/g, ' ').slice(0, 60) + ')')
  /* Fire the stage verb through a REAL click so the menu closes with it. */
  const fired = await page.getByRole('button', { name: /暂存 2|Stage 2/ }).first().click({ timeout: 4000 }).then(() => true).catch(() => false)
  await settle(2500)
  await page.keyboard.press('Escape')
  await settle(300)
  check(fired === true, 'bulk stage verb fired')
  /* Group heads and rows are siblings inside the windowed list — count the
     staged group's rows by walking BOTH kinds in order. */
  const stagedCount = await page.locator('.dig-changes-list .dig-group-head, .dig-changes-list .dig-row-file').evaluateAll((nodes) => {
    let head = null
    let staged = 0
    for (const node of nodes) {
      const text = node.textContent || ''
      if ((node.getAttribute('class') || '').indexOf('dig-group-head') >= 0 || ((node.parentElement && node.parentElement.getAttribute('class')) || '').indexOf('dig-group-head') >= 0) { head = text; continue }
      if (head !== null && head.indexOf('已暂存') >= 0) staged += 1
    }
    return staged
  })
  check(stagedCount >= 3, 'staged group holds the bulk-staged rows (saw ' + stagedCount + ')')

  /* ---- 6. Backspace opens the grouped discard confirm; cancel ---- */
  const rows = changeRows()
  await rows.nth(0).click({ modifiers: ['Meta'] })
  await settle(250)
  if (await rows.count() > 1) await rows.nth(1).click({ modifiers: ['Meta'] })
  await settle(250)
  await page.locator('.dig-changes-list').focus()
  await page.keyboard.press('Backspace')
  await settle(700)
  const dialogVisible = await page.locator('.dig-dialog:visible').count()
  check(dialogVisible === 1, 'Backspace opens the discard confirm')
  if (dialogVisible === 1) {
    const cancel = page.locator('.dig-dialog button').first()
    await cancel.click({ timeout: 5000 })
    await settle(400)
    check(await page.locator('.dig-dialog:visible').count() === 0, 'discard confirm cancels cleanly')
  }

  /* ---- 7. Ctrl+C copies the selected paths ----
     Clear first: Ctrl/Cmd+click on an already-picked row would TOGGLE it out.
     The expected text is the PICKED ROW'S OWN title — the group layout shifts
     as earlier steps stage files, so no positional assumption is allowed. */
  await page.keyboard.press('Escape')
  await settle(300)
  await rows.nth(0).click({ modifiers: ['Meta'] })
  await settle(400)
  const onePath = await page.locator('.dig-row-file.dig-row-selected').first().getAttribute('title')
  const pickedNow = await selectedRows().count()
  await page.evaluate(() => navigator.clipboard.writeText(''))
  await page.keyboard.press('Control+c')
  await settle(600)
  const clip = await page.evaluate(() => navigator.clipboard.readText())
  check(pickedNow === 1 && clip === onePath, 'Ctrl+C copies the selected path (picked ' + pickedNow + ', got "' + clip.slice(0, 50) + '")')
  await page.keyboard.press('Escape')
  await settle(300)

  /* ---- 8. branch tree: pick two, copy names, grouped-delete menu ---- */
  const branchRows = page.locator('.dig-tree .dig-row-local:not(.dig-row-head)')
  const branchCount = await branchRows.count()
  check(branchCount >= 2, 'tree offers local branches to multi-select (saw ' + branchCount + ')')
  if (branchCount >= 2) {
    await branchRows.nth(0).click({ modifiers: ['Meta'] })
    await settle(300)
    await branchRows.nth(1).click({ modifiers: ['Meta'] })
    await settle(300)
    const picked = await page.locator('.dig-tree .dig-row-local.dig-row-selected').count()
    check(picked === 2, 'Ctrl+click picks two branch rows')
    await page.evaluate(() => navigator.clipboard.writeText(''))
    await page.locator('.dig-tree').focus()
    await page.keyboard.press('Control+c')
    await settle(600)
    const names = await page.evaluate(() => navigator.clipboard.readText())
    check(names.split('\n').length === 2, 'Ctrl+C copies both branch names (got "' + names.slice(0, 40) + '")')
    await branchRows.nth(1).click({ button: 'right' })
    await settle(600)
    const deleteOffered = await page.evaluate(() => {
      const buttons = Array.from(document.querySelectorAll('button'))
      return buttons.some((el) => /删除 2|Delete 2/.test((el.textContent || '').trim()) === true)
    })
    check(deleteOffered === true, 'right-click offers the grouped delete')
    await page.keyboard.press('Escape')
    await settle(400)
    await page.keyboard.press('Escape')
    await settle(300)
  }

  /* ---- 9. history: pick two commits, copy hashes, cherry-pick verb ---- */
  const commitRows = page.locator('.dig-history-scroll .dig-commit')
  const commitCount = await commitRows.count()
  check(commitCount >= 2, 'history offers commits to multi-select (saw ' + commitCount + ')')
  /* FRESH-SHIFT (anchorless): the history list has never been clicked, so the
     first Shift+click must span from the FIRST commit (the exact usage the
     user reported as dead — "按住 shift 选择 commit 完全没效果"). */
  if (commitCount >= 5) {
    await commitRows.nth(4).click({ modifiers: ['Shift'] })
    await settle(500)
    check(await page.locator('.dig-history-scroll .dig-commit.dig-commit-selected').count() === 5,
      'Shift+click with no anchor spans the first five commits')
    await page.keyboard.press('Escape')
    await settle(300)
  }
  if (commitCount >= 2) {
    await commitRows.nth(0).click({ modifiers: ['Meta'] })
    await settle(400)
    await commitRows.nth(1).click({ modifiers: ['Meta'] })
    await settle(400)
    const pickedCommits = await page.locator('.dig-history-scroll .dig-commit.dig-commit-selected').count()
    check(pickedCommits === 2, 'Ctrl+click picks two commits')
    await page.evaluate(() => navigator.clipboard.writeText(''))
    await page.locator('.dig-history-scroll').focus()
    await page.keyboard.press('Control+c')
    await settle(600)
    const hashes = await page.evaluate(() => navigator.clipboard.readText())
    check(/^[0-9a-f]{40}\n[0-9a-f]{40}$/.test(hashes.trim()) === true, 'Ctrl+C copies two full hashes')
    await commitRows.nth(1).click({ button: 'right' })
    await settle(600)
    const cherryOffered = await page.evaluate(() => {
      const buttons = Array.from(document.querySelectorAll('button'))
      return buttons.some((el) => /2/.test((el.textContent || '').trim()) === true && /cherry|Cherry|체리/i.test(el.textContent || '') === true)
    })
    check(cherryOffered === true, 'right-click offers cherry-pick for the pair')
    await page.keyboard.press('Escape')
    await settle(400)
    await page.keyboard.press('Escape')
    await settle(300)
  }
} catch (error) {
  failures.push('probe crashed: ' + String(error && error.message ? error.message : error))
  console.log(error)
}

check(pageErrors.length === 0, 'zero uncaught page errors (saw ' + pageErrors.length + ')')
console.log(failures.length === 0 ? 'selection-probe: ALL OK' : 'selection-probe: ' + failures.length + ' FAILURE(S)')
await browser.close()
process.exit(failures.length === 0 ? 0 : 1)
